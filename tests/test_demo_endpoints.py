"""Tests for the demo page, /metrics and /demo/scenarios.

The HTML is not the risk here. The risk is that adding routes breaks the one endpoint that
gates everything, or that the page becomes a G5 liability by putting a URL on screen in
front of a judge. Both are tested explicitly.
"""

from __future__ import annotations

import json
from pathlib import Path

import pytest
from fastapi.testclient import TestClient

from app.cache import Cache
from app.main import app
from backend.matcher.catalog import contains_url

KIT_PATH = Path(__file__).resolve().parents[1] / "student_kit" / "siis_responses.json"


@pytest.fixture
def client():
    with TestClient(app) as test_client:
        yield test_client


# ------------------------------------------------------------------ G2 is sacred -----


def test_health_is_untouched_by_the_new_routes(client):
    """The reason this test exists at all.

    Adding a route at "/" is exactly the moment a catch-all can shadow /health, and G2 is an
    exact-match check whose failure zeroes all 60 automated points and skips every live
    check. Asserted again here rather than trusting that it still works.
    """
    response = client.get("/health")
    assert response.status_code == 200
    assert response.json() == {"status": "ok"}


def test_health_body_has_no_extra_keys(client):
    """A build marker or uptime field here would fail an exact-match gate. It lives on
    /metrics for precisely this reason."""
    assert list(client.get("/health").json()) == ["status"]


def test_troubleshoot_still_works_with_the_new_routes(client):
    from app.validator import validate

    response = client.post(
        "/v1/troubleshoot",
        json={
            "query": "my screen is black",
            "siis_response": {
                "title": "Blank display",
                "content": "## Force a Restart\nPress and hold the Power button.",
            },
        },
    )
    assert response.status_code == 200
    assert validate(response.json())["ok"] is True


# ---------------------------------------------------------------- the demo page -----


def test_root_serves_html(client):
    response = client.get("/")
    assert response.status_code == 200
    assert response.headers["content-type"].startswith("text/html")
    assert "<!doctype html>" in response.text.lower()
    assert "Bixel" in response.text


def test_page_loads_nothing_from_another_origin(client):
    """Deliberate: no CDN, no npm, no build step.

    A demo that fails because a CDN is slow during judging is worse than a plain one, and a
    cross-origin script would also be blocked in an offline container.
    """
    text = client.get("/").text
    assert "script src=" not in text
    assert "//cdn" not in text
    assert "https://" not in text.replace("bixby://", "")


def test_page_only_calls_its_own_origin(client):
    """The service sends no CORS headers, so the page must use relative paths only."""
    text = client.get("/").text
    for path in ('fetch("/v1/troubleshoot"', 'fetch("/metrics")', 'fetch("/demo/scenarios")'):
        assert path in text, f"missing same-origin call: {path}"


def test_page_is_honest_about_the_masked_deeplinks(client):
    """The catalog URIs are Samsung's masked placeholders. A judge who spots a faked Bixby
    launch stops trusting anything else on the page."""
    text = client.get("/").text
    assert "masked" in text
    assert "never generated by the model" in text


